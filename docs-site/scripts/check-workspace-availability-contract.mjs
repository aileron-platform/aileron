function assertManifest(manifest) {
  const availabilityStates = new Set(manifest.availabilityStates);
  const allowedActions = new Set(manifest.allowedActions);

  if (
    manifest.schemaVersion !== 1 ||
    manifest.endpoint?.method !== 'GET' ||
    manifest.actionEndpoint?.method !== 'POST'
  ) {
    throw new Error('Unsupported workspace availability manifest schema.');
  }

  for (const [reasonCode, reason] of Object.entries(manifest.reasonCodes)) {
    if (!availabilityStates.has(reason.availability)) {
      throw new Error(
        `${reasonCode} references unknown availability ${reason.availability}.`,
      );
    }

    for (const action of reason.defaultAllowedActions) {
      if (!allowedActions.has(action)) {
        throw new Error(`${reasonCode} references unknown action ${action}.`);
      }
    }
  }

  const deletion = manifest.deletionProjection;
  const deletionActions = new Set(deletion?.actions);
  const deletionPhases = new Set(deletion?.phases);
  const entryAvailabilities = new Set(deletion?.entry?.availability);
  if (
    deletion?.field !== 'deletion' ||
    deletion.intentEndpoint?.method !== 'DELETE' ||
    deletion.intentEndpoint?.path !== '/api/v1/workspaces/{workspaceId}' ||
    deletion.authorization?.operationId !== 'workspace.delete' ||
    deletion.authorization?.minimumResourceRole !== 'owner' ||
    deletion.intentEndpoint?.confirmationField !== 'confirmationName' ||
    deletion.intentEndpoint?.confirmationMustMatchCurrentWorkspaceName !== true ||
    deletion.intentEndpoint?.confirmationRequiredForRetry !== true ||
    !deletionActions.has('delete') ||
    !deletionActions.has('retry') ||
    JSON.stringify(deletion.phases) !== JSON.stringify(expectedDeletionPhases) ||
    JSON.stringify(Object.keys(deletion.phaseProjection))
      !== JSON.stringify(expectedDeletionPhases) ||
    JSON.stringify(deletion.entry?.allowedActions) !== JSON.stringify(['delete']) ||
    !entryAvailabilities.has('ready') ||
    !entryAvailabilities.has('transitioning') ||
    !entryAvailabilities.has('stopped') ||
    !entryAvailabilities.has('blocked') ||
    deletion.progress?.kind !== 'phase' ||
    deletion.progress?.percentage !== false ||
    JSON.stringify(deletion.progress?.requiredPhases)
      !== JSON.stringify(expectedDeletionPhases) ||
    deletion.automationConvergence?.queued !== 'cancel' ||
    deletion.automationConvergence?.running
      !== 'request_cancel_and_wait_for_terminal' ||
    deletion.automationConvergence?.uncertain
      !== 'fail_and_preserve_workspace' ||
    deletion.idempotency?.inFlight !== 'reuse_existing_attempt' ||
    deletion.idempotency?.failed !== 'explicit_retry_creates_new_attempt' ||
    deletion.idempotency?.acceptedAttemptLocksWrites !== true
  ) {
    throw new Error('Invalid Workspace deletion projection contract.');
  }

  for (const [phase, projection] of Object.entries(deletion.phaseProjection)) {
    if (!deletionPhases.has(phase)) {
      throw new Error(`Unknown Workspace deletion phase ${phase}.`);
    }

    const availabilities = Array.isArray(projection.availability)
      ? projection.availability
      : [projection.availability];
    for (const availability of availabilities) {
      if (!availabilityStates.has(availability)) {
        throw new Error(
          `Workspace deletion phase ${phase} references unknown availability ${availability}.`,
        );
      }
    }

    for (const action of projection.allowedActions) {
      if (!deletionActions.has(action)) {
        throw new Error(
          `Workspace deletion phase ${phase} references unknown action ${action}.`,
        );
      }
    }
  }

  if (
    deletion.completion?.availability !== 'not_found' ||
    deletion.completion?.httpStatus !== 404 ||
    deletion.completion?.workspaceMustBeAbsent !== true ||
    deletion.failure?.availability !== 'blocked' ||
    deletion.failure?.retryable !== true ||
    JSON.stringify(deletion.failure?.allowedActions) !== JSON.stringify(['retry']) ||
    deletion.failure?.preserveWorkspace !== true ||
    deletion.failure?.preservePersistentData !== true ||
    deletion.failure?.clientTimeoutIsNotSuccess !== true ||
    deletion.knowledgeBase?.preserveEntity !== true ||
    deletion.knowledgeBase?.removeAttachmentRelationOnCompletion !== true
  ) {
    throw new Error('Invalid Workspace deletion completion or failure contract.');
  }
}

function formatActions(actions) {
  if (actions.length === 0) {
    return '—';
  }

  return actions.map((action) => `\`${action}\``).join(', ');
}

function renderDeletionProjectionTable(manifest, language) {
  const deletion = manifest.deletionProjection;
  const headers = language === 'zh-TW'
    ? ['deletion phase', 'availability', '允許動作', '語意']
    : ['Deletion phase', 'Availability', 'Allowed actions', 'Semantics'];
  const descriptions = language === 'zh-TW'
    ? {
        queued: '刪除 intent 已接受，等待 worker 執行刪除工作。',
        cancelling_automations: '取消 queued／running Automation，並等待終止結果可確認。',
        stopping_runtime: '停止執行環境；停止未確認前不得清除 Workspace。',
        deleting_resources: '清理 Workspace 專屬資源並提交永久刪除。',
        finalizing: '提交最後的 Workspace／Knowledge Base 關聯清理並確認完成條件。',
      }
    : {
        queued: 'The delete intent was accepted and is waiting for the deletion worker.',
        cancelling_automations: 'Cancel queued and running Automation and wait for a confirmed terminal result.',
        stopping_runtime: 'Stop the execution plane; do not remove the Workspace before stop is confirmed.',
        deleting_resources: 'Clean Workspace-owned resources and commit permanent deletion.',
        finalizing: 'Commit the final Workspace/Knowledge Base relation cleanup and verify completion.',
      };
  const rows = Object.entries(deletion.phaseProjection).map(([phase, projection]) => [
    `\`${phase}\``,
    Array.isArray(projection.availability)
      ? projection.availability.map((value) => `\`${value}\``).join(', ')
      : `\`${projection.availability}\``,
    formatActions(projection.allowedActions),
      descriptions[phase],
  ]);

  const entryHeaders = language === 'zh-TW'
    ? ['投影狀態', 'availability', '允許動作', '語意']
    : ['Projection state', 'Availability', 'Allowed actions', 'Semantics'];
  const entryRows = [
    [
      language === 'zh-TW' ? '刪除入口' : 'Deletion entry',
      deletion.entry.availability.map((value) => `\`${value}\``).join(', '),
      formatActions(deletion.entry.allowedActions),
      language === 'zh-TW'
        ? 'Workspace 仍存在；Owner 可提出 DELETE intent。'
        : 'The Workspace exists; the Owner may submit the DELETE intent.',
    ],
    [
      language === 'zh-TW' ? '失敗結果' : 'Failure outcome',
      '`blocked`',
      formatActions(deletion.failure.allowedActions),
      language === 'zh-TW'
        ? '保留 Workspace 與持久化資料；Owner 可重新確認名稱並以 DELETE 重試。'
        : 'Preserve the Workspace and persistent data; the Owner may reconfirm the name and retry with DELETE.',
    ],
    [
      language === 'zh-TW' ? '完成結果' : 'Completion outcome',
      '`not_found`',
      '—',
      language === 'zh-TW'
        ? 'Workspace 回傳 404；只有此結果可清理 query、導向 fallback 並顯示成功。'
        : 'The Workspace returns 404; only this outcome permits query cleanup, fallback navigation, and success.',
    ],
  ];

  return [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((row) => `| ${row.join(' | ')} |`),
    '',
    `| ${entryHeaders.join(' | ')} |`,
    `| ${entryHeaders.map(() => '---').join(' | ')} |`,
    ...entryRows.map((row) => `| ${row.join(' | ')} |`),
  ].join('\n');
}

function renderContractTable(manifest, language) {
  const headers =
    language === 'zh-TW'
      ? [
          'stable reason code',
          'availability',
          '影響範圍',
          'HTTP',
          '可重試',
          '預設授權動作',
        ]
      : [
          'Stable reason code',
          'Availability',
          'Scope',
          'HTTP',
          'Retryable',
          'Default authorized actions',
        ];
  const rows = Object.entries(manifest.reasonCodes).map(
    ([reasonCode, reason]) => [
      `\`${reasonCode}\``,
      `\`${reason.availability}\``,
      `\`${reason.scope}\``,
      `\`${reason.httpStatus}\``,
      language === 'zh-TW'
        ? reason.retryable
          ? '是'
          : '否'
        : reason.retryable
          ? 'Yes'
          : 'No',
      formatActions(reason.defaultAllowedActions),
    ],
  );

  return [
    startMarker,
    generatedNotice,
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((row) => `| ${row.join(' | ')} |`),
    '',
    language === 'zh-TW'
      ? '### Workspace 永久刪除投影'
      : '### Workspace permanent-deletion projection',
    '',
    renderDeletionProjectionTable(manifest, language),
    endMarker,
  ].join('\n');
}

function replaceGeneratedBlock(source, expectedBlock, documentPath) {
  const startIndex = source.indexOf(startMarker);
  const endIndex = source.indexOf(endMarker);

  if (startIndex === -1 || endIndex === -1 || endIndex < startIndex) {
    throw new Error(`Availability contract markers are invalid in ${documentPath}.`);
  }

  return [
    source.slice(0, startIndex),
    expectedBlock,
    source.slice(endIndex + endMarker.length),
  ].join('');
}

const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
assertManifest(manifest);

const mismatches = [];
for (const document of documents) {
  const source = await readFile(document.path, 'utf8');

  if (
    !source.includes(manifest.endpoint.path) ||
    !source.includes(manifest.actionEndpoint.path)
  ) {
    throw new Error(
      `Availability endpoint contract is missing from ${document.path}.`,
    );
  }

  const expectedBlock = renderContractTable(manifest, document.language);
  const expectedSource = replaceGeneratedBlock(
    source,
    expectedBlock,
    document.path,
  );

  if (source === expectedSource) {
    continue;
  }

  if (writeMode) {
    await writeFile(document.path, expectedSource, 'utf8');
  } else {
    mismatches.push(path.relative(repositoryDirectory, document.path));
  }
}

if (mismatches.length > 0) {
  throw new Error(
    `Workspace availability contract is stale in: ${mismatches.join(', ')}. Run npm run generate:workspace-contract.`,
  );
}

if (writeMode) {
  process.stdout.write('Workspace availability contract documentation updated.\n');
} else {
  process.stdout.write('Workspace availability contract documentation is current.\n');
}
