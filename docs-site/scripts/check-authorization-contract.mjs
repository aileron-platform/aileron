async function snapshotWritableDocuments() {
  const snapshot = new Map();

  async function visit(directory) {
    const entries = await readdir(directory, { withFileTypes: true });
    await Promise.all(entries.map(async (entry) => {
      const entryPath = path.join(directory, entry.name);
      if (entry.isDirectory()) {
        await visit(entryPath);
        return;
      }
      if (entry.isSymbolicLink()) {
        snapshot.set(entryPath, `symlink:${await readlink(entryPath)}`);
        return;
      }
      if (entry.isFile()) {
        const digest = createHash('sha256')
          .update(await readFile(entryPath))
          .digest('hex');
        snapshot.set(entryPath, `file:${digest}`);
      }
    }));
  }

  await Promise.all(writableDocumentRoots.map(visit));
  return snapshot;
}

export function assertOnlyAllowedDocumentChanges(
  beforeSnapshot,
  afterSnapshot,
  allowedPaths,
) {
  const changedPaths = new Set([
    ...beforeSnapshot.keys(),
    ...afterSnapshot.keys(),
  ]);
  const unexpectedChanges = [...changedPaths]
    .filter((filePath) => (
      beforeSnapshot.get(filePath) !== afterSnapshot.get(filePath)
      && !allowedPaths.has(path.resolve(filePath))
    ))
    .sort();
  if (unexpectedChanges.length > 0) {
    throw new Error(
      `Authorization contract generation changed files outside its allow-list: ${unexpectedChanges.join(', ')}`,
    );
  }
}

async function writeFileAtomically(targetPath, content) {
  const resolvedTargetPath = path.resolve(targetPath);
  if (!allowedDocumentPaths.has(resolvedTargetPath)) {
    throw new Error(`Refusing to write outside the authorization document allow-list: ${targetPath}`);
  }

  const temporaryPath = path.join(
    path.dirname(resolvedTargetPath),
    `.${path.basename(resolvedTargetPath)}.${randomUUID()}.tmp`,
  );
  try {
    await writeFile(temporaryPath, content, 'utf8');
    await rename(temporaryPath, resolvedTargetPath);
  } catch (error) {
    await unlink(temporaryPath).catch(() => undefined);
    throw error;
  }
}

function existingGeneratedBlock(source, marker, targetPath) {
  const startMarker = `<!-- authorization-contract:${marker}:start -->`;
  const endMarker = `<!-- authorization-contract:${marker}:end -->`;
  const startIndex = source.indexOf(startMarker);
  const endIndex = source.indexOf(endMarker);
  if (startIndex === -1 && endIndex === -1) {
    return '';
  }
  if (startIndex === -1 || endIndex < startIndex) {
    throw new Error(`Authorization contract markers are invalid in ${targetPath}.`);
  }
  return source.slice(startIndex + startMarker.length, endIndex);
}

function replaceGeneratedBlock(source, marker, rendered, targetPath) {
  const startMarker = `<!-- authorization-contract:${marker}:start -->`;
  const endMarker = `<!-- authorization-contract:${marker}:end -->`;
  const generatedBlock = [
    startMarker,
    generatedNotice,
    rendered,
    endMarker,
  ].join('\n');
  const startIndex = source.indexOf(startMarker);
  const endIndex = source.indexOf(endMarker);

  if (startIndex === -1 && endIndex === -1) {
    return `${source.trimEnd()}\n\n${generatedBlock}\n`;
  }
  if (startIndex === -1 || endIndex < startIndex) {
    throw new Error(`Authorization contract markers are invalid in ${targetPath}.`);
  }
  return [
    source.slice(0, startIndex),
    generatedBlock,
    source.slice(endIndex + endMarker.length),
  ].join('');
}

async function main() {
  assertAuthorizationContracts({
    wireContract,
    operationContract,
    runtimeRouteContract,
  });
  const beforeSnapshot = writeMode
    ? await snapshotWritableDocuments()
    : null;
  const mismatches = [];
  for (const document of documents) {
    const renderedBlocks = new Map();
    for (const language of ['zh-Hant', 'en']) {
      const targetPath = documentPath(document.relativePath, language);
      const source = await readFile(targetPath, 'utf8');
      if (!writeMode && source.includes('TODO_TRANSLATION')) {
        throw new Error(`Untranslated authorization contract content in ${targetPath}.`);
      }
      const renderedBlock = document.render(
        language,
        existingGeneratedBlock(source, document.marker, targetPath),
      );
      renderedBlocks.set(language, renderedBlock);
      const expectedSource = replaceGeneratedBlock(
        source,
        document.marker,
        renderedBlock,
        targetPath,
      );
      if (source === expectedSource) {
        continue;
      }
      if (writeMode) {
        await writeFileAtomically(targetPath, expectedSource);
      } else {
        mismatches.push(path.relative(repositoryDirectory, targetPath));
      }
    }
    assertMarkerIdentifierParity(
      renderedBlocks.get('zh-Hant'),
      renderedBlocks.get('en'),
      document.marker,
    );
  }

  if (beforeSnapshot) {
    assertOnlyAllowedDocumentChanges(
      beforeSnapshot,
      await snapshotWritableDocuments(),
      allowedDocumentPaths,
    );
  }

  if (mismatches.length > 0) {
    throw new Error(
      `Authorization contract documentation is stale in: ${mismatches.join(', ')}. Run npm run generate:authorization-contract.`,
    );
  }

  for (const relativePath of authorizationDocumentPaths) {
    for (const language of ['zh-Hant', 'en']) {
      const targetPath = documentPath(relativePath, language);
      const source = await readFile(targetPath, 'utf8');
      if (source.includes('TODO_TRANSLATION')) {
        throw new Error(
          `Untranslated authorization content in ${path.relative(repositoryDirectory, targetPath)}.`,
        );
      }
      assertNoLegacyAuthorizationTerms(
        source,
        path.relative(repositoryDirectory, targetPath),
      );
    }
  }

  process.stdout.write(
    writeMode
      ? 'Authorization contract documentation updated.\n'
      : 'Authorization contract documentation is current.\n',
  );
}

const invokedScriptPath = process.argv[1]
  ? path.resolve(process.argv[1])
  : null;
if (invokedScriptPath === fileURLToPath(import.meta.url)) {
  await main();
}
