function code(value) {
  return value === null ? '—' : `\`${value}\``;
}

function table(headers, rows) {
  return [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((row) => `| ${row.join(' | ')} |`),
  ].join('\n');
}

function splitMarkdownRow(line) {
  const trimmed = line.trim();
  if (!trimmed.startsWith('|') || !trimmed.endsWith('|')) {
    return [];
  }
  const cells = [];
  let current = '';
  let escaped = false;
  for (const character of trimmed.slice(1, -1)) {
    if (character === '|' && !escaped) {
      cells.push(current.trim());
      current = '';
      continue;
    }
    current += character;
    escaped = character === '\\' && !escaped;
    if (character !== '\\') {
      escaped = false;
    }
  }
  cells.push(current.trim());
  return cells;
}

function extractMarkdownTables(source) {
  const lines = source.split(/\r?\n/);
  const tables = [];
  for (let index = 0; index < lines.length - 1; index += 1) {
    const header = splitMarkdownRow(lines[index]);
    const separator = splitMarkdownRow(lines[index + 1]);
    if (
      header.length === 0
      || separator.length !== header.length
      || separator.some((cell) => !/^:?-{3,}:?$/.test(cell))
    ) {
      continue;
    }
    const tableLines = [lines[index], lines[index + 1]];
    index += 2;
    while (index < lines.length && splitMarkdownRow(lines[index]).length > 0) {
      tableLines.push(lines[index]);
      index += 1;
    }
    tables.push(tableLines.join('\n'));
  }
  return tables;
}

function markerIdentifierOrder(source) {
  return extractMarkdownTables(source).flatMap((markdownTable) => (
    markdownTable
      .split(/\r?\n/)
      .slice(2)
      .map((line) => splitMarkdownRow(line)[0])
      .filter(Boolean)
  ));
}

export function assertMarkerIdentifierParity(
  zhHantBlock,
  englishBlock,
  marker,
) {
  const zhHantIdentifiers = markerIdentifierOrder(zhHantBlock);
  const englishIdentifiers = markerIdentifierOrder(englishBlock);
  if (
    JSON.stringify(zhHantIdentifiers) !== JSON.stringify(englishIdentifiers)
  ) {
    throw new Error(
      `Authorization marker ${marker} identifier order differs between zh-Hant and en.`,
    );
  }
}

const legacyAuthorizationPatterns = [
  /`(?:developer|assistant_user|read_only_user|editor)`/g,
  /`(?:marketplace\.(?:read|write|install|delete)|workspace\.(?:read|write|settings\.manage)|terminal\.use|agent_chat\.use|automation\.execute|browser_automation\.use|knowledge_base\.(?:read|write|manage))`/g,
  /\b(?:tombstoned_at|tombstone cleanup|tombstone_cleanup|tombstone retention)\b/gi,
];

export function assertNoLegacyAuthorizationTerms(source, relativePath) {
  const startMarker = '<!-- authorization-legacy:start -->';
  const endMarker = '<!-- authorization-legacy:end -->';
  const startCount = source.split(startMarker).length - 1;
  const endCount = source.split(endMarker).length - 1;
  if (startCount !== endCount) {
    throw new Error(`Invalid authorization history markers in ${relativePath}.`);
  }
  const currentContractSource = source.replace(
    /<!-- authorization-legacy:start -->[\s\S]*?<!-- authorization-legacy:end -->/g,
    '',
  );
  const legacyMatches = legacyAuthorizationPatterns.flatMap((pattern) => (
    [...currentContractSource.matchAll(pattern)].map((match) => match[0])
  ));
  if (legacyMatches.length > 0) {
    throw new Error(
      `Found legacy authorization identifiers in ${relativePath}: ${[...new Set(legacyMatches)].join(', ')}`,
    );
  }
}

export function renderTableWithDescriptions({
  headers,
  rows,
  descriptionHeader,
  existingTable,
  fallbackDescription,
  preserveDescriptions = true,
  rowKey = (row) => row[0],
}) {
  const existingLines = existingTable?.split(/\r?\n/) ?? [];
  const existingHeader = splitMarkdownRow(existingLines[0] ?? '');
  const hasDescriptionColumn = existingHeader.length > headers.length;
  const existingKeys = new Set();
  const descriptionsByKey = new Map();

  for (const line of existingLines.slice(2)) {
    const cells = splitMarkdownRow(line);
    if (cells.length === 0) {
      continue;
    }
    const existingRow = hasDescriptionColumn ? cells.slice(0, -1) : cells;
    const existingRowKey = rowKey(existingRow);
    existingKeys.add(existingRowKey);
    if (
      preserveDescriptions
      && hasDescriptionColumn
      && cells.length > headers.length
      && cells.at(-1) !== '—'
    ) {
      descriptionsByKey.set(existingRowKey, cells.at(-1));
    }
  }

  const renderedRows = rows.map((row) => {
    const renderedRowKey = rowKey(row);
    const description = preserveDescriptions
      ? descriptionsByKey.get(renderedRowKey)
        ?? (
          existingKeys.has(renderedRowKey)
            ? fallbackDescription(row)
            : 'TODO_TRANSLATION'
        )
      : fallbackDescription(row);
    return [...row, description];
  });
  return table([...headers, descriptionHeader], renderedRows);
}

function renderTablesWithDescriptions(tableDefinitions, existingBlock) {
  const existingTables = extractMarkdownTables(existingBlock);
  return tableDefinitions
    .map((definition, index) => renderTableWithDescriptions({
      ...definition,
      existingTable: existingTables[index],
    }))
    .join('\n\n');
}

function operationRows(scope) {
  return operationContract.requirements
    .filter((requirement) => requirement.scope === scope)
    .map((requirement) => [
      code(requirement.operationId),
      code(requirement.minimumResourceRole),
      code(String(requirement.platformAdminOnly)),
    ]);
}

function errorRows(errorCodes) {
  return errorCodes.map((errorCode) => [code(errorCode)]);
}

function platformRoleDescription(language, row) {
  return language === 'en'
    ? `Platform role ${row[0]}.`
    : `平台角色 ${row[0]}。`;
}

function resourceRoleDescription(language, row) {
  return language === 'en'
    ? `Resource role ${row[0]}.`
    : `資源角色 ${row[0]}。`;
}

function operationDescription(language, row) {
  const [operationId, minimumRole, platformAdminOnly] = row;
  if (minimumRole === '—') {
    return language === 'en'
      ? `${operationId} is a platform operation; Platform Admin only: ${platformAdminOnly}.`
      : `${operationId} 是平台操作；僅限平台管理員：${platformAdminOnly}。`;
  }
  return language === 'en'
    ? `${operationId} requires minimum resource role ${minimumRole}.`
    : `${operationId} 的最低資源角色為 ${minimumRole}。`;
}

function accessSourceDescription(language, row) {
  return language === 'en'
    ? `Authorization access source ${row[0]}.`
    : `授權存取來源 ${row[0]}。`;
}

function authorizationErrorDescription(language, row) {
  return language === 'en'
    ? `Stable authorization error code ${row[0]}.`
    : `穩定授權錯誤碼 ${row[0]}。`;
}

function runtimeRouteDescription(language, row) {
  const [routeTemplate, methods, action, , sensitive] = row;
  return language === 'en'
    ? `${methods} ${routeTemplate} maps to ${action}; sensitive: ${sensitive}.`
    : `${methods} ${routeTemplate} 對應 ${action}；敏感路由：${sensitive}。`;
}

export function groupAuthorizationErrorCodes(errorCodes) {
  return {
    platform: errorCodes.filter((errorCode) => (
      (
        errorCode.startsWith('PLATFORM_')
        && !errorCode.startsWith('PLATFORM_RESOURCE_')
      )
      || errorCode.startsWith('MANAGER_SESSION_')
      || errorCode.startsWith('RESOURCE_')
    )),
    platformResources: errorCodes.filter((errorCode) => (
      errorCode.startsWith('PLATFORM_RESOURCE_')
    )),
    workspace: errorCodes.filter((errorCode) => (
      errorCode.startsWith('WORKSPACE_')
      && !errorCode.startsWith('WORKSPACE_RUNTIME_')
    )),
    knowledgeBase: errorCodes.filter((errorCode) => (
      errorCode.startsWith('KB_') || errorCode.startsWith('KNOWLEDGE_BASE_')
    )),
    runtime: errorCodes.filter((errorCode) => (
      errorCode.startsWith('WORKSPACE_RUNTIME_')
    )),
  };
}

